export const SAMPLE_CONTAINER_ID = 'abc123'.repeat(10) + 'abcd';
export function dockerFixture(path) {
  if (path === '/containers/json')
    return [
      {
        Id: SAMPLE_CONTAINER_ID,
        Names: ['/sample-web'],
        Image: 'sample/nginx:fixture',
        State: 'running',
        Status: 'Up (sample)',
        Labels: { 'dockside.sample': 'true' },
      },
    ];
  if (path.endsWith('/json')) return { RestartCount: 0, Config: { Labels: { 'dockside.sample': 'true' } } };
  if (path.endsWith('/stats'))
    return {
      cpu_stats: { cpu_usage: { total_usage: 200 }, system_cpu_usage: 10000, online_cpus: 2 },
      precpu_stats: { cpu_usage: { total_usage: 100 }, system_cpu_usage: 5000 },
      memory_stats: { usage: 45875200 },
    };
  return null;
}
export function sampleLogFrame() {
  const text = `${new Date().toISOString()} SAMPLE: request handled by development fixture\n`;
  const data = Buffer.from(text);
  const header = Buffer.alloc(8);
  header[0] = 1;
  header.writeUInt32BE(data.length, 4);
  return Buffer.concat([header, data]);
}
